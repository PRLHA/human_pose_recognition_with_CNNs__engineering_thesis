def mpjpe_from_generator(model, generator):
    """
    Computes Mean Per Joint Position Error (MPJPE) over all samples in a generator.
    """
    total_error = 0.0
    num_samples = 0

    for i in range(len(generator)):
        X_batch, Y_batch = generator[i]
        preds = model.predict(X_batch, verbose=0)

        # Reshape to (num_samples, num_joints, 2)
        num_joints = Y_batch.shape[1] // 2
        Y_batch = Y_batch.reshape(-1, num_joints, 2)
        preds = preds.reshape(-1, num_joints, 2)

        # Compute Euclidean distances per joint, average over joints and batch
        errors = np.linalg.norm(Y_batch - preds, axis=-1)
        batch_error = np.sum(errors)

        total_error += batch_error
        num_samples += Y_batch.shape[0]

    mpjpe_value = total_error / (num_samples * num_joints)
    return mpjpe_value



