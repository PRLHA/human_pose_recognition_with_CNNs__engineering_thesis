def build_keypoint_model(input_shape=(512, 512, 3), num_keypoints=16):
    base_model = applications.ResNet50(include_top=False, weights='imagenet', input_shape=input_shape)
    base_model.trainable = False
    inputs = base_model.input
    x = base_model.output

    # Add extra conv layers to enhance feature extraction
    x = Conv2D(512, (3, 3), activation='relu', padding='same')(x)
    x = layers.BatchNormalization()(x)
    x = Conv2D(256, (3, 3), activation='relu', padding='same')(x)
    x = layers.BatchNormalization()(x)
    x = Conv2D(256, (3, 3), activation='relu', padding='same')(x)
    x = layers.BatchNormalization()(x)
    x = Conv2D(256, (3, 3), activation='relu', padding='same')(x)
    x = layers.BatchNormalization()(x)

    x = Conv2D(
        num_keypoints, (1, 1),
        activation=None,
        name='heatmap_conv',
        kernel_regularizer=regularizers.l2(1e-5)
    )(x)
    
    x = layers.BatchNormalization(name='batch_norm')(x)
    x = SpatialSoftmax(name='spatial_softmax')(x)
    x = layers.Dropout(0.3, name='dropout')(x)

    keypoints = SoftArgMaxConv(name='softargmax')(x)
    keypoints = Reshape((num_keypoints * 2,), name='reshape_output')(keypoints)

    model = models.Model(inputs, keypoints)
    return model


